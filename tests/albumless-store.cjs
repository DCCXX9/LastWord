const assert = require('node:assert/strict');
const { createMockWorker } = require('./harness.cjs');
const own={id:'test',url:'https://www.last.fm/user/DCCXX/library'};
const settings={username:'DCCXX',infiniteScroll:true};
(async()=>{
 const legacy={albumlessRules:{old:{since:1}},albumlessScan:{nextPage:94},itunesImportUndo:null,rules:{artists:{},albums:{},tracks:{},albumArtists:{}}};
 const w=createMockWorker({settings,...legacy});
 const req=(op,values={},sender=own)=>w.request('albumless',{op,username:'DCCXX',...values},sender);
 const initial=await req('read');
 assert.equal(initial.enabled,false); assert.deepEqual(initial.rules,{});assert.equal(w.writes,0);
 await Promise.all([req('learn',{tracks:[{artist:'A',track:'One'}]}),req('learn',{tracks:[{artist:'B',track:'Two'}]})]);
 let state=await req('read');assert.equal(Object.keys(state.rules).length,2);
 const id=JSON.stringify(['a','one']), rule=state.rules[id];
 assert.ok(rule.since>=Math.floor(Date.now()/1000)-2,'retrospective learning starts at now, never at an old play');
 await req('learn',{tracks:[{artist:'A',track:'One'}]});assert.deepEqual((await req('read')).rules[id],rule);
 await assert.rejects(req('configure',{enabled:true,revision:state.revision},own),/settings page/);
 const extension={id:'test',url:'chrome-extension://test/albumless.html'};
 state=await req('read');await req('configure',{enabled:true,revision:state.revision},extension);
 await assert.rejects(req('reserve',{item:{artist:'A',track:'One',timestamp:String(rule.since)}}),/future/);
 const item={artist:'A',track:'One',timestamp:String(rule.since+1)};
 const claims=await Promise.all([req('reserve',{item}),req('reserve',{item})]);
 assert.equal(claims.filter(c=>c.claimed).length,1,'one durable attempt across tabs');
 const claim=claims.find(c=>c.claimed);
 await req('settle',{id:claim.id,token:claim.token,phase:'uncertain',reason:'Response interrupted'});
 state=await req('read');assert.equal(state.enabled,false,'an uncertain write pauses corrections');
 await req('configure',{enabled:true,revision:state.revision},extension);
 assert.equal((await req('reserve',{item})).claimed,false,'never replay an uncertain POST automatically');
 await assert.rejects(req('settle',{id:claim.id,token:'wrong',phase:'verified'}),/attempt/);
 await assert.rejects(req('learn',{tracks:[{artist:'X',track:'Y'}]},{id:'test',url:'https://www.last.fm/user/Friend/library'}),/connected/);
 const before=structuredClone(w.data);
 await assert.rejects(req('scan',{expectedPage:1,next:3,total:3,candidates:[]}),/page/);
 assert.deepEqual(w.data,before);
 await req('scan',{expectedPage:1,next:2,total:3,candidates:[{artist:'Old',track:'Blank'}]});
 assert.equal((await req('read')).scan.next,2);
 assert.equal(Object.keys((await req('read')).rules).length,2,'discovery only prepares review candidates');
 await assert.rejects(req('scan',{expectedPage:1,next:2,total:3,candidates:[]}),/another tab/);
 for(const [key,value] of Object.entries(legacy))assert.deepEqual(w.data[key],value,key+' preserved');
 const backup=await w.request('backup');assert.ok(backup.extraStorage.lfmAlbumlessV1);
 await w.externalSet({lfmAlbumlessV1:{version:99}});
 const malformed=structuredClone(w.data);
 await assert.rejects(req('learn',{tracks:[{artist:'A',track:'Bad'}]}),/Export a JSON/);
 assert.deepEqual(w.data,malformed);
 console.log('PASS: future-only rule capture, serialized independent storage, explicit enablement, durable attempt deduplication, resumable review and legacy preservation');
})().catch(e=>{console.error(e);process.exitCode=1;});
